func ed25519HasSmallOrder(pub []byte) bool {
	if len(pub) != ed25519.PublicKeySize {
		return false
	}

	var y [ed25519.PublicKeySize]byte

	copy(y[:], pub)

	// The high bit carries the sign of the x coordinate. It is cleared so that both points sharing a y coordinate
	// match, as does an encoding which sets it for a point whose x coordinate is zero.
	y[ed25519.PublicKeySize-1] &= 0x7f

	// The table holds the y coordinates of the eight points of small order on edwards25519, as libsodium lists them
	// for ge25519_has_small_order. Its last two entries are the non-canonical encodings of 0 and 1 as p and p+1,
	// which are the only such encodings of a small order point as no other y coordinate remains below 2^255 once p
	// is added to it.
	return slices.Contains(ed25519SmallOrderY[:], y)
}

func marshalEd25519PublicKey(pub ed25519.PublicKey) ([]byte, error) {
	return x509.MarshalPKIXPublicKey(pub)
}
